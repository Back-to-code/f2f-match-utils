// Package foldtable builds the rules package's fold table: what every non-ASCII code point becomes
// after lowercasing, removing diacritics and dropping apostrophes. The rules package looks runes up
// in it, so matching needs no Unicode normalisation at runtime.
package foldtable

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"unicode"
	"unicode/utf8"

	"golang.org/x/text/unicode/norm"
)

// OutputFile is relative to the rules package directory, where go generate runs.
const OutputFile = "fold_table.go"

// Letters that NFD leaves whole; folded by hand after the combining marks are gone.
var specialLetters = strings.NewReplacer("ß", "ss", "ø", "o", "æ", "ae", "œ", "oe", "ł", "l")

// Dropped without separating words, so "o.a." is one word and "it's" stays "its".
var dropped = strings.NewReplacer(".", "", "'", "", "’", "", "‘", "", "`", "", "´", "")

// Version is the Unicode version the table is generated from. The norm and unicode tables come from
// the toolchain that runs the generator, and both must agree.
func Version() (string, error) {
	if norm.Version != unicode.Version {
		return "", fmt.Errorf("golang.org/x/text has Unicode %s but the unicode package has %s", norm.Version, unicode.Version)
	}
	return unicode.Version, nil
}

// Fold is the slow reference fold of one code point.
func Fold(r rune) string {
	text := strings.ToLower(string(r))
	if !isASCII(text) {
		var builder strings.Builder
		for _, ch := range norm.NFD.String(text) {
			if !unicode.Is(unicode.Mn, ch) {
				builder.WriteRune(ch)
			}
		}
		text = specialLetters.Replace(builder.String())
	}
	return dropped.Replace(text)
}

func isASCII(text string) bool {
	for idx := range len(text) {
		if text[idx] >= utf8.RuneSelf {
			return false
		}
	}
	return true
}

func isWordByte(ch byte) bool {
	return ('a' <= ch && ch <= 'z') || ('0' <= ch && ch <= '9')
}

func Generate() ([]byte, error) {
	version, err := Version()
	if err != nil {
		return nil, err
	}
	var vanish [][2]rune
	var mappedRunes []rune
	mapped := map[rune]string{}
	for r := rune(utf8.RuneSelf); r <= unicode.MaxRune; r++ {
		if 0xD800 <= r && r <= 0xDFFF {
			continue
		}
		out := Fold(r)
		if out == "" {
			if len(vanish) > 0 && vanish[len(vanish)-1][1] == r-1 {
				vanish[len(vanish)-1][1] = r
			} else {
				vanish = append(vanish, [2]rune{r, r})
			}
			continue
		}
		words := 0
		for idx := range len(out) {
			if isWordByte(out[idx]) {
				words++
			}
		}
		if words == 0 {
			continue
		}
		// The rules package treats a mapped rune as word characters only.
		if words != len(out) {
			return nil, fmt.Errorf("U+%04X folds to %q, a mix of word and other characters", r, out)
		}
		mapped[r] = out
		mappedRunes = append(mappedRunes, r)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by \"go generate ./rules/...\" from Unicode %s; DO NOT EDIT.\n\n", version)
	buf.WriteString("package rules\n\n")
	fmt.Fprintf(&buf, "const foldUnicodeVersion = %q\n\n", version)
	buf.WriteString("var foldVanishRanges = [...][2]rune{\n")
	for _, span := range vanish {
		fmt.Fprintf(&buf, "\t{0x%X, 0x%X},\n", span[0], span[1])
	}
	buf.WriteString("}\n\n")
	buf.WriteString("var foldMapped = map[rune]string{\n")
	for _, r := range mappedRunes {
		fmt.Fprintf(&buf, "\t0x%X: %q,\n", r, mapped[r])
	}
	buf.WriteString("}\n")
	return format.Source(buf.Bytes())
}
