package langtable

import (
	"bytes"
	"fmt"
	"go/format"

	"github.com/Back-to-code/f2f-match-utils/language/internal/langcode"
)

const numbersPerLine = 12

// Generate turns the contents of languages.tsv into the contents of tables_gen.go.
func Generate(src []byte) ([]byte, error) {
	languages, err := ParseTSV(src)
	if err != nil {
		return nil, err
	}

	table, err := Build(languages)
	if err != nil {
		return nil, err
	}

	return Render(table)
}

// Render writes the table as Go source. Everything it emits is an array of integers or a
// map of a couple of hundred entries, so the generated file needs no init function and
// leaves the garbage collector nothing to walk.
func Render(table *Table) ([]byte, error) {
	out := &bytes.Buffer{}

	fmt.Fprint(out, "// Code generated by \"go generate ./language/...\"; DO NOT EDIT.\n")
	fmt.Fprint(out, "// Source: languages.tsv\n\n")
	fmt.Fprint(out, "package language\n\n")

	fmt.Fprint(out, "// nameCount is the number of lookup names: every code, name and alias.\n")
	fmt.Fprintf(out, "const nameCount = %d\n\n", len(table.Names))

	fmt.Fprint(out, "// nameHashes holds the FNV-1a hash of every normalized lookup name, sorted so a\n")
	fmt.Fprint(out, "// lookup is a binary search. nameCodes holds what each one resolves to.\n")
	fmt.Fprint(out, "var nameHashes = [nameCount]uint32{\n")
	renderNumbers(out, len(table.Names), func(i int) uint64 { return uint64(table.Names[i].Hash) })
	fmt.Fprint(out, "}\n\n")

	fmt.Fprint(out, "var nameCodes = [nameCount]uint16{\n")
	err := renderPackedCodes(out, len(table.Names), func(i int) string { return table.Names[i].Code })
	if err != nil {
		return nil, err
	}
	fmt.Fprint(out, "}\n\n")

	fmt.Fprint(out, "// shortCodeCount is the number of languages that have an ISO 639-1 code.\n")
	fmt.Fprintf(out, "const shortCodeCount = %d\n\n", len(table.ShortCodes))

	fmt.Fprint(out, "// shortCodeKeys holds their packed ISO 639-3 codes, sorted. shortCodeValues holds\n")
	fmt.Fprint(out, "// their ISO 639-1 codes as two bytes, in the same order.\n")
	fmt.Fprint(out, "var shortCodeKeys = [shortCodeCount]uint16{\n")
	err = renderPackedCodes(out, len(table.ShortCodes), func(i int) string { return table.ShortCodes[i].Code3 })
	if err != nil {
		return nil, err
	}
	fmt.Fprint(out, "}\n\n")

	fmt.Fprint(out, "var shortCodeValues = [shortCodeCount]uint16{\n")
	renderNumbers(out, len(table.ShortCodes), func(i int) uint64 {
		code := table.ShortCodes[i].Code1
		return uint64(code[0])<<8 | uint64(code[1])
	})
	fmt.Fprint(out, "}\n\n")

	fmt.Fprint(out, "// SupportedLanguages maps the ISO 639-3 code to the Dutch language name. Only the\n")
	fmt.Fprint(out, "// languages in the supported set are in here. To parse a name or a code, use\n")
	fmt.Fprint(out, "// Parse.\n")
	fmt.Fprint(out, "var SupportedLanguages = map[Code]string{\n")
	for _, dutch := range table.Dutch {
		packed, err := langcode.Pack(dutch.Code3)
		if err != nil {
			return nil, err
		}

		// A Code is a packed number, so the code it stands for goes in a comment.
		fmt.Fprintf(out, "%d: %q, // %s\n", packed, dutch.Name, dutch.Code3)
	}
	fmt.Fprint(out, "}\n")

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated source does not parse: %w", err)
	}

	return formatted, nil
}

func renderNumbers(out *bytes.Buffer, count int, at func(int) uint64) {
	for i := range count {
		fmt.Fprintf(out, "%d,", at(i))
		if i%numbersPerLine == numbersPerLine-1 {
			fmt.Fprintln(out)
		}
	}
	fmt.Fprintln(out)
}

func renderPackedCodes(out *bytes.Buffer, count int, at func(int) string) error {
	packed := make([]uint16, count)
	for i := range count {
		value, err := langcode.Pack(at(i))
		if err != nil {
			return err
		}
		packed[i] = value
	}

	renderNumbers(out, count, func(i int) uint64 { return uint64(packed[i]) })

	return nil
}
